def _make(name, frames, delay, final):
    async def handler(cmd):
        for f in frames:
            await cmd.event.edit(f)
            await asyncio.sleep(delay)
        await cmd.event.edit(final)
    return handler


for _n, (_frames, _delay, _final, _desc) in ANIMS.items():
    command(_n, section="fun", desc=_desc)(_make(_n, _frames, _delay, _final))


@command(".عد_تنازلي", section="fun", usage=".عد_تنازلي [ثواني]", desc="عد تنازلي متحرك (حتى 30 ثانية)")
async def countdown(cmd):
    n = cmd.int_arg(5, 1, 30)
    for i in range(n, 0, -1):
        await cmd.event.edit(f"⏳ **{i}**")
        await asyncio.sleep(1)
    await cmd.event.edit("🎉 **انتهى الوقت!**")

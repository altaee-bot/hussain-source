@command(".رقم", section="games", usage=".رقم [من] [الى]", desc="رقم عشوائي (افتراضي 1-100)")
async def number(cmd):
    nums = [int(w) for w in cmd.words if w.lstrip("-").isdigit()]
    lo, hi = (nums[0], nums[1]) if len(nums) >= 2 else (1, nums[0] if nums else 100)
    if lo > hi:
        lo, hi = hi, lo
    await cmd.edit(f"🔢 **الرقم:** `{random.randint(lo, hi)}`  _(من {lo} إلى {hi})_")


@command(".حجر", ".حجرة", section="games", usage=".حجر <حجر|ورقة|مقص>", desc="حجر ورقة مقص ضد ريكو")
async def rps(cmd):
    names = {"حجر": "🪨", "ورقة": "📄", "مقص": "✂️"}
    mine = cmd.args.strip()
    cmd.need(mine in names, "اختار: `.حجر حجر` أو `ورقة` أو `مقص`")
    bot = random.choice(list(names))
    wins = {("حجر", "مقص"), ("ورقة", "حجر"), ("مقص", "ورقة")}
    res = "🤝 تعادل!" if mine == bot else "🏆 فزت!" if (mine, bot) in wins else "😎 فاز ريكو!"
    await cmd.edit(f"{names[mine]} **انت** ⚔️ **ريكو** {names[bot]}\n{LINE}\n{res}")


@command(".نسبة", section="games", usage=".نسبة <شي> (بالرد على شخص أو بدون)",
         desc="نسبة عشوائية لأي صفة: `.نسبة الذكاء` `.نسبة الجمال` `.نسبة الطيبة`")
async def rate(cmd):
    user = await cmd.target(required=False)
    what = (cmd.rest if user is not None and cmd.rest != cmd.args else cmd.args).strip() or "الذكاء"
    who = mention(user) if user else "انت"
    pct = random.randint(0, 100)
    bar = "🟩" * (pct // 10) + "⬜" * (10 - pct // 10)
    await cmd.edit(f"📊 **نسبة {what} عند {who}:**\n{bar}\n**{pct}%**")



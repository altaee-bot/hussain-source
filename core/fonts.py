_GLYPHS = {g for k, m in STYLES.items() if k != "0" for g in m.values()}


def style_time(t_str, style="0"):
    """يحوّل نص الوقت (مثل 01:20) إلى النمط المطلوب."""
    mapping = STYLES[style]
    if style == "0":
        t_str = t_str.upper()
    return "".join(mapping.get(c, c) for c in t_str)


def clean_name(first_name):
    """يرجع الاسم بدون الوقت المزخرف الذي أضافه السورس."""
    name = re.split(r" \| ", first_name or "")[0].strip()
    for i, ch in enumerate(name):
        if ch in _GLYPHS:
            return name[:i].strip()
    return name
